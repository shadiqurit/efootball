CREATE TABLE IF NOT EXISTS USERS (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  EMAIL VARCHAR(254) NOT NULL UNIQUE,
  NAME VARCHAR(100) NOT NULL,
  PASSWORD_HASH VARCHAR(255) NOT NULL,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Original PLAYERS column names and nullability are retained; Oracle types become MySQL types.
CREATE TABLE IF NOT EXISTS PLAYERS (
  PLAYER_ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  FIRST_NAME VARCHAR(100), LAST_NAME VARCHAR(100), NAME VARCHAR(100),
  PLAYER_CODE VARCHAR(100), COUNTRY VARCHAR(100), DOB DATE,
  SUB_POSITION VARCHAR(100), POSITION VARCHAR(100), FOOT VARCHAR(100),
  HEIGHT_CM SMALLINT UNSIGNED, POSITIONS VARCHAR(100), POSITION_CODE VARCHAR(20),
  UPD_DATE DATETIME, UPD_BY INT UNSIGNED,
  UNIQUE KEY uq_player_code (PLAYER_CODE),
  KEY ix_player_name (NAME), KEY ix_player_position (POSITION_CODE), KEY ix_player_country (COUNTRY)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS GAME_ACCOUNTS (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  LABEL VARCHAR(100) NOT NULL, GAME_ID VARCHAR(100) NOT NULL UNIQUE,
  PLATFORM VARCHAR(30) NOT NULL, NOTES VARCHAR(500),
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ASSIGNMENTS (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  GAME_ACCOUNT_ID INT UNSIGNED NOT NULL, PLAYER_ID INT UNSIGNED NOT NULL,
  RATING TINYINT UNSIGNED NOT NULL,
  CREATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UPDATED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_squad_player (GAME_ACCOUNT_ID, PLAYER_ID),
  KEY ix_rating (RATING),
  CONSTRAINT fk_assignment_account FOREIGN KEY (GAME_ACCOUNT_ID) REFERENCES GAME_ACCOUNTS(ID) ON DELETE CASCADE,
  CONSTRAINT fk_assignment_player FOREIGN KEY (PLAYER_ID) REFERENCES PLAYERS(PLAYER_ID) ON DELETE RESTRICT,
  CONSTRAINT ck_rating CHECK (RATING BETWEEN 1 AND 120)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS RATING_HISTORY (
  ID INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, ASSIGNMENT_ID INT UNSIGNED NOT NULL,
  OLD_RATING TINYINT UNSIGNED, NEW_RATING TINYINT UNSIGNED NOT NULL,
  CHANGED_BY INT UNSIGNED NOT NULL, CHANGED_AT DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY ix_history_assignment (ASSIGNMENT_ID, ID),
  CONSTRAINT fk_history_assignment FOREIGN KEY (ASSIGNMENT_ID) REFERENCES ASSIGNMENTS(ID) ON DELETE CASCADE,
  CONSTRAINT fk_history_user FOREIGN KEY (CHANGED_BY) REFERENCES USERS(ID),
  CONSTRAINT ck_history_rating CHECK (NEW_RATING BETWEEN 1 AND 120)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS SESSIONS (
  TOKEN_HASH CHAR(64) PRIMARY KEY, USER_ID INT UNSIGNED NOT NULL, EXPIRES_AT DATETIME NOT NULL,
  KEY ix_session_expiry (EXPIRES_AT),
  CONSTRAINT fk_session_user FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
